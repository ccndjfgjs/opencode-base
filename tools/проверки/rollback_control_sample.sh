#!/bin/sh
# Доказывает отрицательную сторону контрольного образца: если поиск
# сломан, скрипт обязан сказать «ПОИСК СЛОМАН» и выйти с кодом 3,
# а не отчитаться нулём совпадений.
#
# Работает на копии скрипта во временной папке. Настоящий не трогает.

set -e
BASE="$1"
HERE="$2"
SCRIPT="$HERE/count_refs.py"
OUT="$BASE/вывод.txt"

rm -rf "$BASE"
mkdir -p "$BASE"

# Копия кладётся РЯДОМ с оригиналом, а не во временную папку. Скрипт ищет
# папку програмки от своего собственного расположения, и копия в темпе
# обходила пол-дерева: первый вариант пробы висел десять минут и не
# закончился. Место копии здесь — часть доказательства, а не мелочь.
BROKEN="$HERE/.проба-сломаный-поиск.py"
COPIED="$HERE/.проба-поиск-целым.py"
OUT="$BASE/вывод-сломаный.txt"
OUT2="$BASE/вывод-целый.txt"
cp "$SCRIPT" "$BROKEN"
cp "$SCRIPT" "$COPIED"

cleanup() {
    rm -f "$BROKEN" "$COPIED"
}
trap cleanup EXIT

# Ломаем именно поиск: игла становится заведомо отсутствующим словом.
# Всё остальное в скрипте не тронуто — так и должна выглядеть поломка
# поиска снаружи.
sed -i 's/^NEEDLE = "программисту"$/NEEDLE = "што-то-такого-нет-в-базе"/' \
    "$BROKEN"

echo "--- проверяем, что подмена действительно произошла"
if grep -q 'што-то-такого-нет-в-базе' "$BROKEN"; then
    echo "  игла подменена"
else
    echo "  ПОДМЕНА НЕ ПРОШЛА — скрипт изменился, проба бессмысленна"
    exit 2
fi

echo ""
echo "--- гоняем сломанный поиск"
set +e
python "$BROKEN" "$OUT" > "$BASE/stdout1.txt" 2>&1
CODE=$?
set -e
echo "  код выхода: $CODE (ждём 3)"
tail -3 "$OUT" > "$BASE/otvet.txt" || true
while IFS= read -r line; do echo "  | $line"; done < "$BASE/otvet.txt"

echo ""
echo "--- ради сравнения: тот же скрипт без поломки"
set +e
python "$COPIED" "$OUT2" > "$BASE/stdout2.txt" 2>&1
CODE2=$?
set -e
echo "  код выхода: $CODE2 (ждём 0)"

if [ "$CODE" = "3" ] && [ "$CODE2" = "0" ]; then
    echo ""
    echo "ИТОГ: сломанный поиск опознан, отказ вместо нуля."
else
    echo ""
    echo "ИТОГ: НЕ ДОКАЗАНО (сломано $CODE, целый $CODE2)"
    exit 1
fi