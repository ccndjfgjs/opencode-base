"""Мост Unreal Engine больше не запускает npm — и это не поломка.

Что изменилось и почему. В линии 0.6 плагина **EngineWire** MCP-сервер
встроен в сам плагин: автор пишет прямо — «no TypeScript bridge, no
Node.js, no npm», клиент подключается напрямую по адресу
`http://localhost:3000/mcp` (порт меняется в настройках плагина). Пакет
`unreal-engine-mcp-server` в npm остановился на 0.5.30, то есть версии под
релиз 0.6 там просто нет. Старый путь через npm относится к линии 0.5 со
старым плагином McpAutomationBridge, который программа не ставит.

Поэтому этот файл остаётся **только как объяснение**. Он нужен не для
работы, а на случай, если в настройках opencode ещё осталась старая
команда с этим файлом: вместо загадочной ошибки npm человек прочитает, что
делать.

Что делать, если увидели это сообщение:

1. Открой вкладку **MCP**, выбери строку **Unreal Engine**.
2. Нажми **«Настроить автоматически»**: программа проверит плагин в проекте
   и живым запросом спросит адрес сервера.
3. Нажми **«Включить»** — в настройки opencode впишется адрес
   `http://127.0.0.1:3000/mcp`.
4. Мост отвечает, **пока открыт редактор** с плагином EngineWire.

stdout — протокол. Всё остальное — в stderr.
"""

from __future__ import annotations

import sys

PREFIX = "unreal-bridge"

MESSAGE = (
    "Мост Unreal больше не запускает npm: в линии 0.6 сервер встроен в плагин "
    "EngineWire, и клиент ходит к нему по адресу. Эта строка в настройках "
    "opencode осталась от старой версии. Открой вкладку MCP, выбери Unreal "
    "Engine, нажми «Настроить автоматически», потом «Включить». Подробности — "
    "в тексте этого файла."
)


def main() -> int:
    print(MESSAGE, file=sys.stderr)
    print("Мост Unreal: нужен открытый редактор с плагином EngineWire, "
          "адрес http://127.0.0.1:3000/mcp (порт меняется в настройках "
          "плагина).", file=sys.stderr)
    return 1


if __name__ == "__main__":
    sys.exit(main())
